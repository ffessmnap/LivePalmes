"use strict";
require("./helpers/offline-network");
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path");
const { guard } = require("../tools/a3-test-public-access-mail-witness");
const env = { TARGET_FIREBASE_PROJECT: "livepalmes-test", GCLOUD_PROJECT: "livepalmes-test", GOOGLE_CLOUD_PROJECT: "livepalmes-test",
  GITHUB_REF: "refs/heads/main", GITHUB_RUN_ATTEMPT: "1", CONFIRMATION: "livepalmes-test", GITHUB_SHA: "a".repeat(40), EXPECTED_COMMIT: "a".repeat(40) };
guard(env);
for (const key of Object.keys(env)) assert.throws(() => guard({ ...env, [key]: "invalid" }), key);
const workflow = require("./firestore-rules/node_modules/js-yaml").load(fs.readFileSync(path.join(__dirname, "../.github/workflows/livepalmes-test-public-access-proof.yml"), "utf8"));
assert.deepEqual(Object.keys(workflow.on), ["workflow_dispatch"]);
assert.deepEqual(workflow.permissions, { contents: "read", actions: "read" });
assert.equal(workflow.jobs.verify.environment, "firebase-test");
assert.equal(workflow.concurrency.group, "livepalmes-test-backend");
assert.equal(workflow.concurrency["cancel-in-progress"], false);
assert(workflow.jobs.verify.if.includes("github.run_attempt == 1"));
assert(workflow.jobs.verify.if.includes("inputs.expected_commit == github.sha"));
const steps = workflow.jobs.verify.steps;
assert.equal(steps.filter(s => s.uses?.startsWith("actions/checkout"))[1].with.ref, "1670b49db7528b33714a5d2441009f49516a1809");
const commands = steps.map(step => step.run || "").join("\n");
assert.doesNotMatch(commands, /firebase\s+deploy|gcloud\s+(functions\s+(deploy|delete)|.*set-iam)|sendMail|runTransaction/);
assert(steps.findIndex(s => s.run?.includes("build-a3-test-recovery-archive.js")) < steps.findIndex(s => s.uses?.startsWith("google-github-actions/auth")));
const upload = steps.find(s => s.uses?.startsWith("actions/upload-artifact"));
assert.equal(upload.with.name, "a3-test-public-access-proof");
assert(upload.with.path.endsWith("/a3-test-public-access-proof.json"));
assert.equal(upload.with["if-no-files-found"], "error");
const wrapper = require("../tools/build-a3-test-recovery-archive").labelledWrapper('const names = ["fixture"];\n');
assert(wrapper.includes('"livepalmes-commit": "1670b49db7528b33714a5d2441009f49516a1809"'));
assert(wrapper.includes('if (!fn.__endpoint) throw new Error("Endpoint absent")'));
console.log("A3.2 recovery workflow: protected TEST/main, pinned application, offline reconstruction, read-only commands and dedicated sanitized artifact verified.");
