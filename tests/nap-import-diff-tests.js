"use strict";
const assert = require("node:assert/strict");
const { planImportDiff } = require("../functions/nap-import-diff");
const old = { id: 973, nageur: 168, compet: 2, course: "100SF", cat: "HSE", tps: "14200", points: "0", newpoints: "0", passage: 0, club: "106", relais: 0, pid: null, classement: 1 };
const { id, ...incoming } = old;
const args = { competitionId: 2, existing: [old], incoming: [{ ...incoming, tps: "014200", points: 0 }] };
let plan = planImportDiff(args);
assert.equal(plan.summary.unchanged, 1); assert.equal(plan.unchanged[0].row.tps, "14200"); assert.equal(plan.requiresReplacementConfirmation, false);
plan = planImportDiff({ ...args, incoming: [{ ...incoming, tps: "014100" }] });
assert.deepEqual(plan.summary, { before: 1, after: 1, unchanged: 0, additions: 1, removals: 1 });
assert.equal(plan.removals[0].id, 973); assert.equal(plan.requiresReplacementConfirmation, true);
assert.notEqual(plan.previewFingerprint, planImportDiff(args).previewFingerprint);
const duplicate = { ...old, id: 974 };
plan = planImportDiff({ ...args, existing: [duplicate, old] });
assert.equal(plan.unchanged[0].performanceId, 973); assert.equal(plan.removals[0].id, 974, "duplicate multiplicity must not disappear from preview");
assert.equal(plan.expectedFingerprint, planImportDiff({ ...args, existing: [old, duplicate] }).expectedFingerprint);
assert.equal(planImportDiff({ ...args, existing: [] }).requiresReplacementConfirmation, false);
for (const change of [{ ignoredRows: 1 }, { unresolvedRows: 1 }, { existing: [old, old] }, { existing: [{ ...old, compet: 3 }] }, { incoming: [{ ...incoming, compet: 3 }] }, { incoming: [] }]) assert.throws(() => planImportDiff({ ...args, ...change }));
assert.throws(() => planImportDiff({ ...args, incoming: Array(5001).fill(incoming) }), /limite/);
assert.equal(old.tps, "14200");
console.log("NAP import differences: unchanged native ids/times, explicit missing results, duplicate multiplicity, stable previews and incomplete-file refusal passed.");
