"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const XLSX = require("../performances/public/vendor/xlsx.full.min.js");
const context = { window: {}, structuredClone };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, "../assets/livepalmes-engagement-qualifications.js"), "utf8"), context);
const api = context.window.LivePalmesEngagementQualifications;
const events = [{ code: "100SF", type: "individual", categories: ["C", "J"] }];
const rows = [["Femmes"], ["Catégorie", "100 SF"], ["C", "01:23.45"], ["J", ""], ["Hommes"], ["Catégorie", "100 SF"], ["C", "LIBRE"]];
let result = api.importRows(rows, events, ["C", "J"]);
assert.equal(result.errors.length, 0);
assert.equal(result.values["C|F|100SF"], 8345);
assert.equal(result.values["C|M|100SF"], null);
assert.equal(Object.hasOwn(result.values, "J|F|100SF"), false);
const bad = structuredClone(rows); bad[2][1] = "01:99.00";
assert.ok(api.importRows(bad, events, ["C"]).errors.length);
const numeric = structuredClone(rows); numeric[2][1] = 83.45 / 86400;
assert.equal(api.importRows(numeric, events, ["C"]).values["C|F|100SF"], 8345);
assert.ok(api.importRows([...rows, ["C", "12345"]], events, ["C"]).errors.length);
assert.equal(api.importRows(rows, events, []).ignored.length, 2);
const group = { pools: ["50"], electronicOnly: true };
assert.equal(api.sourceState({ pool: "25", chrono: "E" }, group), "excluded");
assert.equal(api.sourceState({ pool: "50", chrono: "manual" }, group), "excluded");
assert.equal(api.sourceState({ pool: "50", chrono: "E" }, group), "compatible");
assert.equal(api.sourceState({ pool: "50" }, group), "unknown");
const template = XLSX.read(fs.readFileSync(path.join(__dirname, "../docs/Trame_minima_LivePalmes.xlsx"))), sheet = template.Sheets.Minima;
assert.deepEqual(template.SheetNames, ["Minima"]);
const grid = XLSX.utils.sheet_to_json(sheet, { header: 1, raw: true, defval: null });
grid[10][2] = "01:23.45"; // C, 100 SF, Femmes
grid[31][2] = "LIBRE"; // C, 100 SF, Hommes
result = api.importRows(grid, events, ["C"]);
assert.equal(result.errors.length, 0);
assert.equal(result.values["C|F|100SF"], 8345);
assert.equal(result.values["C|M|100SF"], null);
const mount = { innerHTML: "" };
const makeGroup = (categories) => ({ ...group, categories, mode: "each", competitionIds: [] });
api.editor(mount, { national: true, events, rules: { enabled: true, groups: [makeGroup(["J"]), makeGroup(["C"])] } });
assert.ok(mount.innerHTML.indexOf("<th>C</th>") < mount.innerHTML.indexOf("<th>J</th>"));
console.log("Import minima : trame validée, temps, blancs, erreurs, ordre et filtres OK.");
