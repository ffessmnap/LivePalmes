"use strict";
const assert = require("node:assert/strict");
const { seal, open } = require("../tools/production-backup-crypto");
const original = Buffer.from("code et configuration sans donnees metier");
const encrypted = seal(original, "test-key-not-a-real-credential");
assert(!encrypted.includes(original));
assert.deepEqual(open(encrypted, "test-key-not-a-real-credential"), original);
assert.throws(() => open(encrypted, "wrong-key"));
const damaged = Buffer.from(encrypted); damaged[damaged.length - 1] ^= 1;
assert.throws(() => open(damaged, "test-key-not-a-real-credential"));
console.log("Sauvegarde: chiffrement, restauration, mauvaise cle et alteration verifies.");
const { generateKeyPairSync } = require('node:crypto');
const transfer = require('../tools/direct-backup-transfer');
const first = generateKeyPairSync('rsa', { modulusLength:2048 });
const second = generateKeyPairSync('rsa', { modulusLength:2048 });
const envelope = transfer.wrap(original, { first:first.publicKey, second:second.publicKey });
assert.deepEqual(transfer.unwrap(envelope, { private_key_id:'second', private_key:second.privateKey }), original);
assert.throws(() => transfer.unwrap(envelope, { private_key_id:'absent', private_key:first.privateKey }));
assert.throws(() => transfer.unwrap(envelope, { private_key_id:'first', private_key:second.privateKey }));
const damagedTransfer = { ...envelope, ciphertext:Buffer.from('altered').toString('base64') };
assert.throws(() => transfer.unwrap(damagedTransfer, { private_key_id:'first', private_key:first.privateKey }));
console.log('Transfert Direct chiffre pour les cles de sauvegarde existantes, cle et contenu invalides refuses.');
