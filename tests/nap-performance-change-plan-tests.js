"use strict";
const assert = require("node:assert/strict");
const { fingerprint, planChange } = require("../functions/nap-performance-change-plan");
const row = { id: 973, nageur: 168, compet: 2, course: "100SF", cat: "S", tps: "14200", points: 0, newpoints: 0, passage: 0, club: "106", relais: 0, pid: null, classement: 1 };
const input = { performanceId: row.id, expectedFingerprint: fingerprint(row), reason: "Correction verifiee", action: "correct", patch: { classement: 2 } };
const plan = planChange({ row, input });
assert.equal(plan.after.tps, "14200", "correcting another field must never pad or change an old time");
assert.equal(row.classement, 1, "planning must not mutate its before image");
assert.deepEqual(plan.before, row);
assert.equal(plan.after.classement, 2);
assert.throws(() => planChange({ row: { ...row, tps: "14300" }, input }), /change/);
assert.throws(() => planChange({ row, hidden: true, input }), /change/);
assert.throws(() => planChange({ row, input: { ...input, reason: " " } }), /Motif/);
assert.throws(() => planChange({ row, input: { ...input, patch: { nageur: 42 } } }), /champ/);
assert.throws(() => planChange({ row, input: { ...input, patch: { date: "2026-11-07" } } }), /champ/);
assert.throws(() => planChange({ row, input: { ...input, patch: { tps: "1:42.00" } } }), /Temps/);
assert.throws(() => planChange({ row, input: { ...input, patch: { tps: "16000" } } }), /Temps/);
assert.throws(() => planChange({ row, input: { ...input, patch: { classement: 1 } } }), /Aucune/);
const hide = { ...input, patch: undefined, action: "hide" };
assert.equal(planChange({ row, input: hide }).hiddenAfter, true);
assert.deepEqual(planChange({ row, input: hide }).after, row);
assert.throws(() => planChange({ row, input: { ...hide, patch: { tps: "14000" } } }), /aucun champ/);
assert.equal(planChange({ row, hidden: true, input: { ...hide, action: "restore", expectedFingerprint: fingerprint(row, true) } }).hiddenAfter, false);
const remove = { ...hide, action: "delete", confirmDeletion: true };
assert.throws(() => planChange({ row, input: remove }), /national/);
assert.throws(() => planChange({ row, national: true, input: { ...remove, confirmDeletion: false } }), /confirmation/);
assert.equal(planChange({ row, national: true, input: remove }).after, null);
assert.throws(() => planChange({ row: { ...row, id: "973" }, input }), /Identifiant/);
assert.throws(() => planChange({ row: { id: 973 }, input }), /incomplete/);
console.log("NAP performance plans: concurrency, native time preservation, explicit patches, reversible visibility and national deletion passed.");
