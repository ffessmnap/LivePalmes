"use strict";
const assert=require("node:assert/strict");
const {planComposition}=require("../functions/nap-relay-composition-plan");
const pack={competitionId:5141,clubId:"106",swimmers:[1,2,3,4,5].map(id=>({id,clubId:"106"})),inscriptions:[1,2,3,4].map(nageur=>({id:nageur,compet:5141,nageur})),relays:[{id:12,compet:5141,categorie:999,club:"106",course:261,tps:"000315"}],members:[{id:21,relais:12,pos:5,nageur:1}]};
const native={compet:5141,categorie:0,club:"106",course:261,tps:"031500"};
const input={action:"create",native,members:[1,2,3,4].map((nageur,index)=>({nageur,pos:index+1}))};
const unchanged=JSON.stringify(pack);
const create=planComposition(pack,input);
assert.equal(create.after.club,106,"Native relay club column is INT");
assert.equal(create.action,"create");assert.ok(!Object.hasOwn(create.after,"id"),"never guess an auto-increment identifier");
assert.equal(create.membersAfter.length,4);
assert.equal(planComposition(pack,{...input,members:[]}).membersAfter.length,0);
const compose=planComposition(pack,{...input,action:"compose",relayId:12});
assert.equal(compose.before.categorie,999);assert.equal(compose.before.tps,"000315");assert.equal(compose.membersBefore[0].pos,5);
assert.equal(JSON.stringify(pack),unchanged,"no historical data is rewritten by planning");
assert.throws(()=>planComposition(pack,{...input,members:[{nageur:5,pos:0},...input.members.slice(1)]}),/selectionne/);
assert.throws(()=>planComposition(pack,{...input,members:[input.members[0],...input.members.slice(0,3)]}),/uniques/);
assert.throws(()=>planComposition(pack,{...input,members:input.members.slice(0,3)}),/Quatre/);
assert.throws(()=>planComposition(pack,{...input,members:input.members.map((member,index)=>({...member,pos:index}))}),/position/,"New relay positions must match the verified native 1..4 contract");
assert.throws(()=>planComposition(pack,{...input,native:{...native,club:"48"}}),/club/);
assert.throws(()=>planComposition(pack,{...input,native:{...native,tps:"10000000"}}),/valide/);
assert.throws(()=>planComposition(pack,{...input,native:{...native,id:99}}),/identifiant/);
assert.throws(()=>planComposition(pack,{...input,action:"compose",relayId:13}),/existant/);
console.log("Relay creation/composition mapping: selected club swimmers, zero/four members, no guessed id, preserved historic witnesses and explicit scoped target; no database.");
