"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const crypto = require("node:crypto");
const zlib = require("node:zlib");
const { EventEmitter } = require("node:events");
const { PassThrough } = require("node:stream");
const b = require("../tools/nap-backup");
const config = require("../tools/nap-backup-config.json");
const { open } = require("../tools/production-backup-crypto");
const tables = [{ name: "nageurs", type: "BASE TABLE", engine: "MyISAM", dataBytes: 200, indexBytes: 100 }, { name: "livepalmes_history", type: "BASE TABLE", engine: "InnoDB", dataBytes: 200, indexBytes: 100 }];
async function main() {
  assert.equal(config.enabled, false, "Preparation must remain inactive until a separate activation change");
  await assert.rejects(b.main({}, ["--backup"]), /BACKUP_DISABLED/, "No credentials or database access before activation guard");
  assert.throws(() => b.backupGate({ enabled: true }, {}), /BACKUP_NOT_AUTHORIZED/);
  assert.throws(() => b.backupGate({ enabled: true }, { GITHUB_REF: "refs/heads/feature", NAP_BACKUP_CONFIRMATION: b.CONFIRMATION }), /BACKUP_NOT_AUTHORIZED/);
  b.backupGate({ enabled: true }, { GITHUB_REF: "refs/heads/main", NAP_BACKUP_CONFIRMATION: b.CONFIRMATION });
  const key = crypto.randomBytes(32);
  assert.deepEqual(b.encryptionKey({ NAP_BACKUP_ENCRYPTION_KEY: key.toString("base64") }), key);
  assert.throws(() => b.encryptionKey({ NAP_BACKUP_ENCRYPTION_KEY: "weak" }), /ENCRYPTION_KEY_REQUIRED/);
  const plan = b.planTables(tables);
  assert.equal(plan.bytes, 600);
  assert.equal(plan.lockSql, "LOCK TABLES `nageurs` READ, `livepalmes_history` READ");
  assert.throws(() => b.planTables([...tables, tables[0]]), /DUPLICATE/);
  assert.throws(() => b.planTables([{ ...tables[0], engine: "FEDERATED" }]), /UNSUPPORTED/);
  assert.throws(() => b.planTables([{ ...tables[0], type: "VIEW" }]), /UNSUPPORTED/);
  assert.throws(() => b.planTables(tables, { ...config, maxDatabaseBytes: 1 }), /BUDGET/);
  assert.throws(() => b.planTables(tables, { ...config, maxTables: 1 }), /BUDGET/);
  const options = b.dumpOptions(tables.map(t => t.name));
  assert.equal(options[0], "--defaults-extra-file=/run/nap-client.cnf");
  assert(options.includes("--skip-lock-tables"));
  assert(options.includes("--hex-blob"));
  assert(options.includes("--no-tablespaces"));
  assert(options.includes("--skip-routines"));
  assert(!options.some(o => o.includes("password") || o === "--single-transaction" || o === "--all-databases" || o === "--lock-all-tables"));
  assert.throws(() => b.dumpOptions(["--all-databases"]), /INVALID/);
  const metadataQueries = [];
  function metadataConnection({ version = "5.7.30", tls = "fixture-cipher", routine = false } = {}) {
    return { async query({ sql }) {
      metadataQueries.push(sql);
      if (sql.startsWith("SELECT VERSION")) return [[{ version, databaseName: "nage-palmes", tableLocks: 1 }]];
      if (sql.includes("information_schema.TABLES")) return [tables];
      if (sql === "SHOW GRANTS") return [[{ grant: "GRANT ALL PRIVILEGES ON `nage-palmes`.* TO 'fixture' IDENTIFIED BY PASSWORD 'never-persist-this'" }]];
      if (sql.includes("Ssl_cipher")) return [[{ Value: tls }]];
      if (sql.includes("ROUTINES") && routine) return [[{ ROUTINE_NAME: "unexpected" }]];
      return [[]];
    } };
  }
  const metadata = await b.inspect(metadataConnection());
  assert.equal(metadataQueries.length, 7);
  assert.equal(metadata.plan.count, 2);
  assert(!JSON.stringify(metadata).includes("never-persist-this"));
  assert(metadataQueries.every(sql => /^(SELECT|SHOW) /.test(sql)));
  await assert.rejects(b.inspect(metadataConnection({ version: "8.4.0" })), /RUNTIME_DRIFT/);
  await assert.rejects(b.inspect(metadataConnection({ tls: "" })), /TLS_REQUIRED/);
  await assert.rejects(b.inspect(metadataConnection({ routine: true })), /STORED_OBJECTS_REQUIRE_REVIEW/);
  const events = [];
  const connection = { async query({ sql }) { events.push(sql); return [[]]; }, destroy() { events.push("unlock"); } };
  const packed = zlib.gzipSync(Buffer.from("CREATE TABLE fixture (id INT); INSERT INTO fixture VALUES (1);"));
  const result = await b.lockedExport({ connection, plan, dump: async () => { events.push("export"); return packed; }, stop: () => events.push("stop") });
  assert.equal(result, packed);
  assert(events.indexOf("export") > events.indexOf(plan.lockSql));
  assert(events.indexOf("unlock") > events.indexOf("export"));
  const failed = [];
  await assert.rejects(b.lockedExport({ connection: { async query() {}, destroy() { failed.push("unlock"); } }, plan, dump: async () => { throw new Error("dump failed"); }, stop: () => failed.push("stop") }), /dump failed/);
  assert.deepEqual(failed, ["unlock", "stop"]);
  const locked = [];
  await assert.rejects(b.lockedExport({ connection: { async query() { throw new Error("lock denied"); }, destroy() { locked.push("unlock"); } }, plan, dump: async () => { assert.fail("Export after failed lock"); }, stop() {} }), /lock denied/);
  assert.deepEqual(locked, ["unlock"]);
  let finish;
  await assert.rejects(b.lockedExport({ connection: { async query() {}, destroy() { finish?.(); } }, plan, settings: { ...config, maxLockMilliseconds: 10 }, dump: () => new Promise(resolve => { finish = () => resolve(packed); }), stop() {} }), /LOCK_TIME_BUDGET/);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "nap-backup-fixture-"));
  try {
    const saved = await b.saveEncrypted({ packed, key, folder: "fixture-folder", outputDir: dir, drive: { async upload(folder, name, bytes) { events.push("upload"); assert(events.indexOf("upload") > events.indexOf("unlock")); assert.equal(folder, "fixture-folder"); assert.deepEqual(open(bytes, key), packed); const damaged = Buffer.from(bytes); damaged[damaged.length - 1] ^= 1; assert.throws(() => open(damaged, key)); return { id: "fixture-file", bytes: bytes.length }; } } });
    assert(saved.file.endsWith(".sql.gz.enc"));
    assert.deepEqual(open(fs.readFileSync(path.join(dir, saved.file)), key), packed);
    await assert.rejects(b.saveEncrypted({ packed, key, folder: "fixture-folder", outputDir: dir, drive: { async upload() { throw new Error("Drive unavailable"); } } }), /Drive unavailable/);
    assert.equal(fs.readdirSync(dir).length, 2, "Keep encrypted recovery copy on upload failure");
    assert(fs.readdirSync(dir).every(name => name.endsWith(".enc")));
  } finally { for (const name of fs.readdirSync(dir)) fs.unlinkSync(path.join(dir, name)); fs.rmdirSync(dir); }
  const encrypted = Buffer.from("encrypted-fixture");
  const md5 = crypto.createHash("md5").update(encrypted).digest("hex");
  let call = 0;
  const drive = b.driveClient("fixture-token", async (url, options) => {
    call++;
    assert(url.includes("supportsAllDrives=true"));
    assert.equal(options.headers.Authorization, "Bearer fixture-token");
    if (call === 1) return { ok: true, json: async () => ({ id: "folder", driveId: "shared-drive", mimeType: "application/vnd.google-apps.folder", capabilities: { canAddChildren: true } }) };
    if (call === 2) { assert.equal(options.method, "POST"); assert(options.headers["Content-Type"].startsWith("multipart/related")); return { ok: true, json: async () => ({ id: "file" }) }; }
    return { ok: true, json: async () => ({ id: "file", parents: ["folder"], size: encrypted.length, md5Checksum: md5 }) };
  });
  await drive.checkFolder("folder");
  await drive.upload("folder", "fixture.enc", encrypted);
  assert.equal(call, 3);
  await assert.rejects(b.driveClient("fixture", async () => ({ ok: true, json: async () => ({ mimeType: "application/vnd.google-apps.folder", capabilities: { canAddChildren: true } }) })).checkFolder("folder"), /SHARED_DRIVE/);
  await assert.rejects(b.driveClient("fixture", async () => ({ ok: false, status: 403 })).checkFolder("folder"), /REMOTE_HTTP_403/);
  let uploadCall = 0;
  await assert.rejects(b.driveClient("fixture", async () => ({ ok: true, json: async () => ++uploadCall === 1 ? { id: "file" } : { parents: ["folder"], size: encrypted.length, md5Checksum: "corrupt" } })).upload("folder", "fixture.enc", encrypted), /VERIFICATION_FAILED/);
  function fakeChild() { const child = new EventEmitter(); child.stdout = new PassThrough(); child.stderr = new PassThrough(); return child; }
  const child = fakeChild();
  const collecting = b.collectDump(child);
  child.stdout.end("fixture SQL"); child.stderr.end(); setImmediate(() => child.emit("exit", 0));
  assert.equal(zlib.gunzipSync(await collecting).toString(), "fixture SQL");
  const broken = fakeChild();
  const brokenPromise = b.collectDump(broken);
  broken.stdout.end("partial"); broken.stderr.end(); setImmediate(() => broken.emit("exit", 2));
  await assert.rejects(brokenPromise, /DUMP_PROCESS_FAILED/);
  const oversized = fakeChild();
  const oversizedPromise = b.collectDump(oversized, { ...config, maxSqlBytes: 1 });
  oversized.stdout.end("too large"); oversized.stderr.end(); setImmediate(() => oversized.emit("exit", 0));
  await assert.rejects(oversizedPromise, /SQL_BUDGET/);
  const workflow = fs.readFileSync(path.join(__dirname, "../.github/workflows/nap-backup-drive.yml"), "utf8");
  assert(!/^\s*schedule:/m.test(workflow), "No automatic export before activation");
  assert(!workflow.includes("workflow_run:") && !workflow.includes("push:") && !workflow.includes("pull_request:"));
  assert(workflow.includes("outputs/nap-backups/*.sql.gz.enc"));
  console.log("NAP backup: activation guards, scoped locks, timeout, release on failure, encrypted recovery, Drive verification and bounded export verified offline.");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
