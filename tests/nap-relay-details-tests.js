"use strict";
const assert=require("node:assert/strict");
const {detail,changed}=require("../functions/nap-relay-details");
const relay={id:99,compet:5141,club:"106",course:261,categorie:0,tps:"031500"};
const raw={existingSetting:{keep:true}};
const extra=changed(raw,relay,{category:"J",genderMode:"mixed"});
assert.deepEqual(detail(relay,extra),{category:"J",genderMode:"mixed"});
assert.deepEqual(detail({...relay,tps:"032000"},extra),{category:"J",genderMode:"mixed"},"Native time changes do not erase the declared category");
assert.equal(detail({...relay,course:262},extra),null,"Stale companions never reinterpret a changed native relay");
assert.equal(detail({...relay,club:"48"},extra),null);
assert.deepEqual(extra.existingSetting,raw.existingSetting);
assert.equal(Object.hasOwn(raw,"relay_details_v1"),false);
assert.equal(detail(relay,changed(extra,relay,null)),null);
assert.equal(detail(relay,"invalid"),null);
assert.throws(()=>changed("invalid",relay,{category:"J",genderMode:"mixed"}));
assert.throws(()=>changed(raw,relay,{category:"invented",genderMode:"mixed"}),/Categorie/);
const {entryItem}=require("../functions/nap-portal-workspaces");
const pack={competitionId:"5141",clubId:"106",swimmers:[],inscriptions:[],individual:[],leaders:[],members:[],officials:[],relays:[{...relay,course_code:"4X100BI Mixte",sexe:"0"}],options:{submission_metadata:extra},readAt:"2026-10-07T00:00:00.000Z"};
assert.equal(entryItem(pack,{},()=>"").relays[0].category,"J");
assert.equal(entryItem({...pack,options:null},{},()=>"").relays[0].category,"NAP-0","No category is invented for an old relay");
console.log("Relay age detail: shared native identity, preserved unrelated settings, stale detail ignored and invalid writes refused; no database.");
