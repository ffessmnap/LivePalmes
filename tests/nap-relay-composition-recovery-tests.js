"use strict";
const assert=require("node:assert/strict");
const {remainingComposition:remaining}=require("../functions/nap-relay-composition-recovery");
const after={compet:5141,categorie:0,club:"106",course:261,tps:"031500"};
const target=[1,2,3,4].map((nageur,index)=>({nageur,pos:index+1}));
const create={action:"create",after,membersAfter:target};
const relay={id:99,...after};
const members=target.map((member,index)=>({id:index+100,relais:99,...member}));
assert.equal(remaining(create,99,[relay],[]).additions.length,4);
assert.equal(remaining(create,99,[relay],members.slice(0,2)).additions.length,2);
assert.equal(remaining(create,99,[relay],members).complete,true);
assert.throws(()=>remaining(create,99,[],[]),/verifier/);
assert.throws(()=>remaining(create,99,[relay],[...members,{id:200,relais:99,pos:5,nageur:8}]),/nouveau/);
assert.throws(()=>remaining(create,99,[relay],[...members,{...members[0],id:200}]),/dupliquee/);
const before={...relay,tps:"000315",categorie:999};
const old={id:55,relais:99,pos:5,nageur:8};
const compose={action:"compose",relayId:99,before,after:{id:99,...after},membersBefore:[old],membersAfter:target};
assert.equal(remaining(compose,99,[before],[old]).update,true);
assert.equal(remaining(compose,99,[relay],[old,...members.slice(0,2)]).removals.length,1);
assert.equal(remaining(compose,99,[relay],members).complete,true);
assert.throws(()=>remaining(compose,99,[{...relay,club:"48"}],members),/change/);
assert.throws(()=>remaining(compose,99,[relay],[{...old,nageur:7}]),/nouveau/);
assert.throws(()=>remaining(compose,100,[{...relay,id:100}],[]),/incompatible/);
console.log("Relay composition recovery: generated-id requirement, partial member insert/removal, desired existing members retained, duplicates and concurrent changes refused; no database.");
