"use strict";
const assert=require("node:assert/strict");
const {planRelayChanges}=require("../functions/nap-relay-entry-plan");
const pack={competitionId:5140,clubId:"48",relays:[{id:12,compet:5140,categorie:0,club:"48",course:261,tps:"000315"},{id:13,compet:5140,categorie:999,club:"48",course:261,tps:"000340"}],members:[{id:21,relais:12,pos:0,nageur:912},{id:22,relais:12,pos:5,nageur:913}]};
const original=JSON.stringify(pack);
const timed=planRelayChanges(pack,[{relayId:12,action:"time",time:"031500"}]);
assert.equal(timed.plans.length,1);
assert.equal(timed.plans[0].before.tps,"000315");
assert.equal(timed.plans[0].after.tps,"031500");
assert.equal(timed.plans[0].after.categorie,0);
assert.deepEqual(timed.plans[0].membersBefore.map(row=>row.pos),[0,5]);
assert.equal(JSON.stringify(pack),original,"Planning never rewrites historic rows or unrelated relays");
const removed=planRelayChanges(pack,[{relayId:13,action:"remove"}]);
assert.equal(removed.plans[0].before.categorie,999,"Removal does not reinterpret an unknown historic category");
assert.equal(removed.plans[0].remove,true);
assert.equal(planRelayChanges(pack,[{relayId:12,action:"time",time:"000315"}]).plans.length,0);
assert.throws(()=>planRelayChanges(pack,[{relayId:14,action:"remove"}]),/absent/);
assert.throws(()=>planRelayChanges(pack,[{relayId:12,action:"remove"},{relayId:12,action:"remove"}]),/deux/);
assert.throws(()=>planRelayChanges(pack,[{relayId:12,action:"time",time:"016000"}]),/Temps/);
assert.throws(()=>planRelayChanges(pack,[{relayId:12,action:"time",time:"10000000"}]),/Temps/,"Native varchar(6) must never truncate a longer time");
assert.throws(()=>planRelayChanges({...pack,relays:[{...pack.relays[0],club:"49"}]},[]),/hors/);
assert.throws(()=>planRelayChanges(pack,[{relayId:12,action:"remove",time:"031500"}]),/Retrait/);
console.log("Native relay plan: explicit correction/removal, historic times/categories/positions retained, foreign scope and duplicate changes refused; no database access");
